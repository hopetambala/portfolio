#!/usr/bin/env node
// Generates src/css/dlite-theme.css from style-dictionary-dlite-tokens.
// Run: npm run tokens  (also auto-runs before build/develop/start)
const fs = require("fs");
const path = require("path");

const PKG = "style-dictionary-dlite-tokens";
function findPkgRoot() {
  let dir = __dirname;
  for (let i = 0; i < 8; i++) {
    const candidate = path.join(dir, "node_modules", PKG);
    if (fs.existsSync(path.join(candidate, "package.json"))) return candidate;
    dir = path.dirname(dir);
  }
  throw new Error(
    `Could not locate ${PKG} in node_modules. Run \`npm install ${PKG}\`.`
  );
}
const WEB_DIR = path.join(findPkgRoot(), "dist", "web");
const OUT_FILE = path.join(__dirname, "..", "src", "css", "dlite-theme.css");

const DEFAULT_BRAND = "survivor/default";

function headingFontFor(brandPath) {
  const family = brandPath.startsWith("kooky/")
    ? '"Recoleta"'
    : brandPath.startsWith("puente/")
    ? '"Plus Jakarta Sans"'
    : brandPath.startsWith("sneaks/")
    ? '"Space Grotesk"'
    : '"Fraunces"'; // survivor/* and any future brand
  return `${family}, Georgia, "Times New Roman", serif`;
}

function readVars(file) {
  const css = fs.readFileSync(file, "utf8");
  const open = css.indexOf("{");
  const close = css.lastIndexOf("}");
  if (open === -1 || close === -1) return "";
  const lines = css
    .slice(open + 1, close)
    .split("\n")
    .map((line) => {
      const trimmed = line.trim();
      return trimmed ? `  ${trimmed}` : "";
    })
    .filter((line, i, arr) => !(line === "" && (i === 0 || arr[i - 1] === "")));
  while (lines.length && lines[0] === "") lines.shift();
  while (lines.length && lines[lines.length - 1] === "") lines.pop();
  return lines.join("\n");
}

function block(selector, body) {
  return `${selector} {\n${body}\n}\n`;
}

// Sneaks intentionally keeps its "primary"/"brand" tokens near-black/near-white
// (its real product uses that as a splash/ink color, with action-primary as the
// only red) — see style-dictionary-dlite/tokens/brands/sneaks.tokens.json. This
// site's editorial.css only has a single --brand accent variable (sourced from
// semantic-color-primary) driving every visible brand moment, so representing
// Sneaks with the neutral color would make it look unthemed here. Re-point
// primary/brand at this combo's own action-primary (and fix the paired "on"
// text color for contrast) — scoped to this generated file only, never touching
// the published token package other apps depend on.
function sneaksActionOverride(brandPath, vars) {
  if (!brandPath.startsWith("sneaks/")) return "";
  const match = vars.match(
    /--tk-dlite-semantic-color-action-primary:\s*(#[0-9a-fA-F]{3,8})\s*;/
  );
  if (!match) return "";
  const actionHex = match[1];
  return [
    `  --tk-dlite-semantic-color-primary: ${actionHex};`,
    `  --tk-dlite-semantic-color-brand: ${actionHex};`,
    `  --tk-dlite-semantic-color-text-on-primary: #ffffff;`,
    `  --tk-dlite-semantic-color-text-on-brand: #ffffff;`,
  ].join("\n");
}

function buildCombo(brandPath, mode) {
  const file = path.join(
    WEB_DIR,
    brandPath,
    mode === "dark" ? "variables.dark.css" : "variables.css"
  );
  if (!fs.existsSync(file)) return null;
  const vars = readVars(file);
  const fontOverride = `  --tk-dlite-semantic-typography-font-heading: ${headingFontFor(
    brandPath
  )};`;
  const actionOverride = sneaksActionOverride(brandPath, vars);
  return [vars, fontOverride, actionOverride].filter(Boolean).join("\n");
}

function main() {
  const manifest = JSON.parse(
    fs.readFileSync(path.join(WEB_DIR, "manifest.json"), "utf8")
  );
  const brands = manifest.brands.map((b) => b.path);

  const out = [
    "/**",
    " * AUTO-GENERATED by scripts/generate-dlite-theme.js — DO NOT EDIT BY HAND.",
    " * Source: style-dictionary-dlite-tokens (dist/web). Run `npm run tokens`.",
    " * All brand/theme x light/dark combos, scoped by [data-brand][data-mode].",
    " */",
    "",
  ];

  const def = buildCombo(DEFAULT_BRAND, "light");
  out.push(block(":root", def));
  out.push("");

  for (const brandPath of brands) {
    for (const mode of ["light", "dark"]) {
      const body = buildCombo(brandPath, mode);
      if (!body) continue;
      out.push(
        block(
          `[data-brand="${brandPath}"][data-mode="${mode}"]`,
          body
        )
      );
    }
  }

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, out.join("\n"), "utf8");
  const combos = brands.length * 2;
  console.log(
    `[dlite] wrote ${path.relative(
      path.join(__dirname, ".."),
      OUT_FILE
    )} (${brands.length} brands, ${combos} combos)`
  );
}

main();
