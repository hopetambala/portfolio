#!/usr/bin/env node
/**
 * Reads each theme's variables.css and variables.dark.css from the
 * style-dictionary-dlite-tokens package, transforms the :root selector
 * to a [data-theme][data-mode] attribute selector, and writes the result
 * to src/css/themes/themes.css.
 *
 * Run after updating the package version:
 *   node scripts/generate-theme-css.js
 */

const fs = require('fs');
const path = require('path');

const PKG_WEB = path.resolve(__dirname, '../node_modules/style-dictionary-dlite-tokens/dist/web');
const OUT_FILE = path.resolve(__dirname, '../src/css/themes/themes.css');

const THEMES = [
  { brand: 'kooky', theme: 'default', id: 'kooky' },
  { brand: 'puente', theme: 'default', id: 'puente' },
  { brand: 'survivor', theme: 'default', id: 'survivor' },
  { brand: 'survivor', theme: 'jungle', id: 'survivor-jungle' },
  { brand: 'survivor', theme: 'winter-holiday', id: 'survivor-winter-holiday' },
];

const blocks = [];

for (const { brand, theme, id } of THEMES) {
  const base = path.join(PKG_WEB, brand, theme);

  for (const [file, mode] of [['variables.css', 'light'], ['variables.dark.css', 'dark']]) {
    const filePath = path.join(base, file);
    if (!fs.existsSync(filePath)) {
      console.warn(`  SKIP (not found): ${filePath}`);
      continue;
    }
    const css = fs.readFileSync(filePath, 'utf8');
    const scoped = css
      .replace(/\/\*[\s\S]*?\*\//g, '') // strip block comments
      .replace(/:root\s*\{/, `[data-theme="${id}"][data-mode="${mode}"] {`);

    blocks.push(`/* ${id} — ${mode} */\n${scoped.trim()}\n`);
    console.log(`  OK: ${id}/${mode}`);
  }
}

const header = `/**
 * Auto-generated by scripts/generate-theme-css.js
 * Source: style-dictionary-dlite-tokens
 * DO NOT EDIT DIRECTLY — re-run the script after updating the package.
 */\n\n`;

fs.writeFileSync(OUT_FILE, header + blocks.join('\n'));
console.log(`\nWrote ${blocks.length} theme blocks to ${OUT_FILE}`);
